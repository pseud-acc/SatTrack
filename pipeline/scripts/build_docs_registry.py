"""Build the dbt docs registry (transform/docs/columns/*.md) from the sourced column definitions.

Source of truth: docs/column_definitions/*.md, one file per source origin (see 00_overview.md). Each file holds
"## Batch <id>: ..." sections with one markdown table of columns; every section cites the publisher's documentation.

Layout: each origin file docs/column_definitions/<origin>.md produces transform/docs/columns/<origin>.md with one
{% docs col__<name> %} block per column name defined in it. 00_overview.md produces nothing.

One block per name (dbt rejects duplicate docs names). Deterministic rule: origin files are read in ORIGINS order,
sections and rows in file order; the first row that defines a name wins, and the block goes into that row's origin
file. Rows whose definition starts with "(shared block" never define a name; they point at the defining row.
Later definitions of the same name are ignored (listed with --verbose when their text differs).

Block text = the row's definition (bold markers removed) + a "Source:" line:
  - SatTrack-derived sections (the table has a "Model / macro" column): "SatTrack-derived: see <models>",
    plus the publishers of the inputs that the definition names (GCAT, Space-Track, pycountry, GeoNames);
  - otherwise the section's keyed source bullet "- `key`: ..." matching the prefix of the row's source column
    (e.g. `orgs` for "orgs.Code"), else the section's "Source:" line (else its unkeyed "Sources:" bullets).
    The URLs of that source text are cited; a source without a URL is cited as written.

Modes:
  (default)  write transform/docs/columns/*.md and remove stale generated files there.
  --check    regenerate in memory; exit 1 if a committed registry file differs or is missing/stale, if a yml
             column's doc('col__x') has no block, or if a model/source column in a yml has no description.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "docs" / "column_definitions"
OUT_DIR = ROOT / "transform" / "docs" / "columns"
MODELS_DIR = ROOT / "transform" / "models"
ORIGINS = [  # read order = precedence for names defined in several origins
    "gcat__satcat_psatcat",
    "gcat__currentcat",
    "gcat__launchlog",
    "gcat__orgs_sites_lv",
    "spacetrack__gp",
    "spacetrack__code_tables",
    "reference__labels_countries_cities",
    "sattrack__derived",
    "sattrack__metadata",
]
IDENT = re.compile(r"^[a-z_][a-z0-9_]*$")
METADATA = {"_loaded_at", "_run_id", "_source_url", "_source_updated_at", "_source_row_number", "_source_file"}
URL = re.compile(r"https?://[^\s)>,;]+")
HEADER = "{{#- Generated by scripts/build_docs_registry.py from docs/column_definitions/{0}.md. Do not edit by hand. -#}}\n"
PUBLISHERS = [  # (pattern in a derived definition, citation) for the inputs of SatTrack-derived columns
    (r"\bGCAT\b", "GCAT https://planet4589.org/space/gcat/"),
    (r"\bGP\b|Space-Track", "Space-Track https://www.space-track.org/documentation"),
    (r"pycountry|\bISO\b", "pycountry https://pypi.org/project/pycountry/"),
    (r"GeoNames", "GeoNames https://download.geonames.org/export/dump/readme.txt"),
]


def cells(line: str) -> list[str]:
    inner = line.strip()[1:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", inner)]


def names_in(cell: str) -> list[str]:
    cell = re.sub(r"\*\(.*?\)\*", "", cell)          # drop "*(existing)*" / "*(was x)*" markers
    cell = re.sub(r"\(domain `[^`]*`\)", "", cell)    # "(domain `x`)" qualifies a name; it isn't one
    return [n for n in re.findall(r"`([^`]+)`", cell) if IDENT.match(n) and (not n.startswith("_") or n in METADATA)]


def cite(text: str) -> str:
    urls = [u.rstrip(".") for u in URL.findall(text)]
    return "; ".join(dict.fromkeys(urls)) if urls else text.strip().rstrip(".")


def section_sources(preamble: str) -> tuple[str | None, dict[str, str]]:
    default, keyed, unkeyed, in_sources = None, {}, [], False
    for line in preamble.splitlines():
        if line.startswith("Source: "):
            default = default or line[len("Source: "):]
        elif line.rstrip().endswith(":") and line.startswith("Sources"):
            in_sources = True
        elif m := re.match(r"^- ((?:`\w+`(?:, )?)+): (.+)$", line):
            for k in re.findall(r"`(\w+)`", m.group(1)):
                keyed[k] = m.group(2)
        elif in_sources and line.startswith("- "):
            unkeyed.append(line[2:])
        elif not line.strip():
            in_sources = False
    if default is None and unkeyed:
        default = " ".join(unkeyed)
    return default, keyed


def parse_rows(origin: str, md: str):
    """Yield (name, block_text, batch, row_no, definition, is_shared) for every name in every table row."""
    for m in re.finditer(r"^## (Batch (\w+): .+?)\n(.*?)(?=^## |\Z)", md, flags=re.M | re.S):
        batch, body = f"Batch {m.group(2)}", m.group(3)
        lines = body.splitlines()
        first = next((i for i, l in enumerate(lines) if l.startswith("| ")), None)
        if first is None:
            continue
        default, keyed = section_sources("\n".join(lines[:first]))
        rows = [l for l in lines[first:] if l.startswith("| ") and not l.startswith("|---")]
        hdr = [h.lower() for h in cells(rows[0])]
        name_i = next(i for i, h in enumerate(hdr) if "name" in h or h == "column")
        def_i = next(i for i, h in enumerate(hdr) if "definition" in h)
        model_i = next((i for i, h in enumerate(hdr) if "model" in h), None)
        src_i = 1 if model_i is None else None
        if model_i is None and default is None and not keyed:
            raise SystemExit(f"{origin}.md {batch}: no 'Source:' line or keyed source bullets")
        for line in rows[1:]:
            c = cells(line)
            if len(c) <= max(name_i, def_i):
                continue
            definition = c[def_i].replace("\\|", "|")
            shared = definition.startswith("(shared block")
            plain = re.sub(r"\*\*(.+?)\*\*", r"\1", definition)
            if model_i is not None:
                models = re.findall(r"`([^`]+)`", c[model_i])
                inputs = [p for pat, p in PUBLISHERS if re.search(pat, plain)]
                source = "SatTrack-derived" + (": see " + ", ".join(f"`{x}`" for x in models) if models else "")
                if inputs and origin != "sattrack__metadata":  # load metadata describe the load, not the data
                    source += ". Inputs: " + "; ".join(inputs)
            else:
                key = re.match(r"[A-Za-z_]+", c[src_i])
                text = keyed.get(key.group(0)) if key else None
                source = cite(text if text is not None else (default or ""))
            block = f"{plain}\n\nSource: {source} ({batch})."
            for n in names_in(c[name_i]):
                yield n, block, batch, c[0], definition, shared


def build() -> tuple[dict[str, str], dict[str, tuple[str, str]], list[str]]:
    """Return ({origin: registry text}, {name: (origin, batch)}, notes on differing later definitions)."""
    owner: dict[str, tuple[str, str]] = {}
    blocks: dict[str, dict[str, str]] = {o: {} for o in ORIGINS}
    notes = []
    missing = [o for o in ORIGINS if not (SRC_DIR / f"{o}.md").exists()]
    if missing:
        raise SystemExit(f"missing definition files: {missing}")
    extra = sorted(p.stem for p in SRC_DIR.glob("*.md") if p.stem not in ORIGINS and not p.stem.startswith("00_"))
    if extra:
        raise SystemExit(f"definition files not in ORIGINS: {extra}")
    for origin in ORIGINS:
        for n, block, batch, row, definition, shared in parse_rows(origin, (SRC_DIR / f"{origin}.md").read_text(encoding="utf-8")):
            if shared:
                continue
            if n not in owner:
                owner[n] = (origin, batch)
                blocks[origin][n] = block
            elif block.split("\n\nSource:")[0] != blocks[owner[n][0]][n].split("\n\nSource:")[0]:
                notes.append(f"{n}: {batch} #{row} ({origin}) also defines it; block kept from {owner[n][1]} ({owner[n][0]})")
    texts = {}
    for origin in ORIGINS:
        body = "".join(f"{{% docs col__{n} %}}\n{blocks[origin][n]}\n{{% enddocs %}}\n\n" for n in sorted(blocks[origin]))
        texts[origin] = HEADER.format(origin) + "\n" + body
    return texts, owner, notes


def yml_columns() -> list[tuple[str, str, str, str | None]]:
    """(yml file, model/source table, column, description or None) for every column listed in a model/source yml.

    A small indentation-based reader (the pipeline venv has no PyYAML); ymls are block style by house rule.
    """
    out = []
    for path in sorted(MODELS_DIR.rglob("*.yml")):
        lines = path.read_text(encoding="utf-8").splitlines()
        owners: list[tuple[int, str]] = []          # (indent, name) of enclosing "- name:" items
        cols_indent = None                          # indent of the active "columns:" key
        item_indent = None                          # indent of its "- name:" items
        current = None                              # [model, column, description]
        for raw in lines + ["__end__:"]:
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            ind = len(raw) - len(raw.lstrip())
            if cols_indent is not None and ind <= cols_indent:
                if current:
                    out.append((path.name, *current))
                cols_indent, item_indent, current = None, None, None
            if cols_indent is not None:
                m = re.match(r"^(\s*)- name: ['\"]?([^'\"\s]+)", raw)
                if m and (item_indent is None or len(m.group(1)) == item_indent):
                    if current:
                        out.append((path.name, *current))
                    item_indent = len(m.group(1))
                    current = [owners[-1][1] if owners else "?", m.group(2), None]
                    continue
                d = re.match(r"^\s*description:\s*(.*)$", raw)
                if d and current and ind == (item_indent or 0) + 2:
                    val = d.group(1).strip()
                    current[2] = val if val not in ("", "''", '""', ">", "|", ">-", "|-") else (val or None)
                elif current and current[2] in (">", "|", ">-", "|-") and ind > (item_indent or 0) + 2:
                    current[2] = raw.strip()
                continue
            m = re.match(r"^(\s*)- name: ['\"]?([^'\"\s]+)", raw)
            if m:
                owners = [o for o in owners if o[0] < len(m.group(1))] + [(len(m.group(1)), m.group(2))]
            if re.match(r"^\s*columns:\s*$", raw):
                cols_indent, item_indent = ind, None
    return out


def check(texts: dict[str, str]) -> int:
    problems = []
    for origin, text in texts.items():
        f = OUT_DIR / f"{origin}.md"
        if not f.exists():
            problems.append(f"missing registry file: {f.relative_to(ROOT)}")
        elif f.read_text(encoding="utf-8") != text:
            problems.append(f"registry out of date: {f.relative_to(ROOT)} (run scripts/build_docs_registry.py)")
    for f in sorted(OUT_DIR.glob("*.md")) if OUT_DIR.exists() else []:
        if f.stem not in texts:
            problems.append(f"stale registry file: {f.relative_to(ROOT)}")
    names = set()
    for text in texts.values():
        names |= set(re.findall(r"\{% docs col__(\w+) %\}", text))
    undocumented, no_desc = [], []
    for yml, model, col, desc in yml_columns():
        ref = re.search(r"doc\(\s*['\"]col__(\w+)['\"]\s*\)", desc or "")
        if ref and ref.group(1) not in names:
            problems.append(f"{yml}: {model}.{col} uses doc('col__{ref.group(1)}'), which has no block")
        if not (desc or "").strip("'\" "):
            (undocumented if col in names else no_desc).append(f"{model}.{col}")
    if undocumented:
        problems.append(f"{len(undocumented)} yml columns have no description (a col__ block exists; link it): "
                        + ", ".join(undocumented))
    if no_desc:
        problems.append(f"{len(no_desc)} yml columns have no description and no col__ block: " + ", ".join(no_desc))
    for p in problems:
        print(f"CHECK FAILED: {p}")
    if not problems:
        print(f"check ok: {len(texts)} registry files, {len(names)} column blocks, every yml column described")
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    ap.add_argument("--verbose", action="store_true", help="list names defined again in later rows")
    args = ap.parse_args()
    texts, owner, notes = build()
    if args.verbose:
        for n in notes:
            print(f"note: {n}")
    if args.check:
        return check(texts)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for origin, text in texts.items():
        (OUT_DIR / f"{origin}.md").write_text(text, encoding="utf-8", newline="\n")
    for f in OUT_DIR.glob("*.md"):
        if f.stem not in texts and f.read_text(encoding="utf-8").startswith("{#- Generated by scripts/build_docs_registry.py"):
            f.unlink()
            print(f"removed stale {f.relative_to(ROOT)}")
    print(f"wrote {len(texts)} files to {OUT_DIR.relative_to(ROOT)} ({len(owner)} column blocks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
